// Builds the paste bundle: appsscript/dist/Code.gs (the studio and curriculum constants generated from content/, then
// appsscript/src/*.gs in a fixed order) and appsscript/dist/appsscript.json (the manifest).
//
//   node appsscript/scripts/build.mjs          write the bundle
//   node appsscript/scripts/build.mjs --check  exit 1 if the committed bundle is out of date
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
export const SOURCES = ['Main.gs', 'Validate.gs', 'Store.gs', 'Auth.gs', 'Studio.gs', 'Practice.gs', 'Intake.gs', 'Routes.gs', 'Setup.gs', 'Reset.gs'];
export const CODE_PATH = join(ROOT, 'dist', 'Code.gs');
export const MANIFEST_PATH = join(ROOT, 'dist', 'appsscript.json');

/** A content/ file as a .gs constant. */
function contentConstant(name, file) {
  const content = JSON.parse(readFileSync(join(ROOT, '..', 'content', file), 'utf8'));
  return '// ---------- generated from content/' + file + ' ----------\n\n' +
    'const ' + name + ' = ' + JSON.stringify(content, null, 2) + ';\n';
}

export function bundle() {
  const header = [
    '/**',
    ' * @OnlyCurrentDoc',
    ' *',
    " * Satt Chitt Anand: the studio app's backend, an Apps Script web app over this spreadsheet.",
    ' * Paste this whole file over Code.gs, run setup() once, then deploy it as a web app (appsscript/README.md).',
    ' * @OnlyCurrentDoc above limits the script to this one spreadsheet.',
    ' *',
    ' * Generated by appsscript/scripts/build.mjs from appsscript/src/*.gs, content/studio.json and content/curriculum.json:',
    ' * change those and rebuild, not this file.',
    ' */',
    '',
  ].join('\n');
  const parts = [contentConstant('STUDIO', 'studio.json'), contentConstant('CURRICULUM', 'curriculum.json')]
    .concat(SOURCES.map((name) => readFileSync(join(ROOT, 'src', name), 'utf8')));
  return { code: header + '\n' + parts.join('\n'), manifest: readFileSync(join(ROOT, 'src', 'appsscript.json'), 'utf8') };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const { code, manifest } = bundle();
  const outputs = [[CODE_PATH, code], [MANIFEST_PATH, manifest]];
  if (process.argv.includes('--check')) {
    const stale = outputs.filter(([path, text]) => {
      try {
        return readFileSync(path, 'utf8') !== text;
      } catch {
        return true;
      }
    });
    if (stale.length) {
      console.error('Out of date: ' + stale.map(([path]) => path).join(', ') + '. Run node appsscript/scripts/build.mjs');
      process.exit(1);
    }
    console.log('dist/ is up to date');
  } else {
    mkdirSync(join(ROOT, 'dist'), { recursive: true });
    outputs.forEach(([path, text]) => writeFileSync(path, text));
    console.log('wrote ' + CODE_PATH + ' (' + code.length + ' characters) and ' + MANIFEST_PATH);
  }
}
